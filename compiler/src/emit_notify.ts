/**
 * BoneScript Notification Service Emitter
 * Generates src/notify.ts — fires on event emissions.
 */

import * as IR from "./ir";

function toPascalCase(s: string): string {
  return s.replace(/(^|[-_\s])(\w)/g, (_, __, c: string) => c.toUpperCase());
}

export function emitNotifyService(system: IR.IRSystem): string {
  const lines: string[] = [];

  lines.push(`// Generated by BoneScript compiler.`);
  lines.push(`// Notification service — fires on event emissions.`);
  lines.push(`// Configure NOTIFY_PROVIDER=resend|sendgrid|log (default: log)`);
  lines.push(`// Set NOTIFY_API_KEY and NOTIFY_FROM_EMAIL in .env`);
  lines.push(``);
  lines.push(`import { SystemEvent } from "./events";`);
  lines.push(``);
  lines.push(`export type NotifyProvider = "resend" | "sendgrid" | "webhook" | "log";`);
  lines.push(``);
  lines.push(`const PROVIDER = (process.env.NOTIFY_PROVIDER || "log") as NotifyProvider;`);
  lines.push(`const API_KEY = process.env.NOTIFY_API_KEY || "";`);
  lines.push(`const FROM_EMAIL = process.env.NOTIFY_FROM_EMAIL || "noreply@example.com";`);
  lines.push(`const WEBHOOK_URL = process.env.NOTIFY_WEBHOOK_URL || "";`);
  lines.push(`const WEBHOOK_SECRET = process.env.NOTIFY_WEBHOOK_SECRET || "";`);
  lines.push(``);
  lines.push(`export interface NotifyMessage {`);
  lines.push(`  to: string;`);
  lines.push(`  subject: string;`);
  lines.push(`  body: string;`);
  lines.push(`}`);
  lines.push(``);
  // HTML-escape helper. Used to render arbitrary event payload data inside an
  // HTML email body without enabling HTML/JS injection in clients that render
  // it. Subject lines are also escaped for consistency.
  lines.push(`function escapeHtml(s: string): string {`);
  lines.push(`  return s`);
  lines.push(`    .replace(/&/g, "&amp;")`);
  lines.push(`    .replace(/</g, "&lt;")`);
  lines.push(`    .replace(/>/g, "&gt;")`);
  lines.push(`    .replace(/"/g, "&quot;")`);
  lines.push(`    .replace(/'/g, "&#39;");`);
  lines.push(`}`);
  lines.push(``);
  // Conservative email validation. Rejects empty input, multiple addresses,
  // and CRLF that would let a caller inject extra headers into the request body
  // sent to Resend / SendGrid.
  lines.push(`const __EMAIL_RE = /^[A-Za-z0-9._%+\\-]+@[A-Za-z0-9.\\-]+\\.[A-Za-z]{2,}$/;`);
  lines.push(`function isValidEmail(addr: string): boolean {`);
  lines.push(`  if (!addr || addr.length > 254) return false;`);
  lines.push(`  if (/[\\r\\n]/.test(addr)) return false;`);
  lines.push(`  return __EMAIL_RE.test(addr);`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`async function sendEmail(msg: NotifyMessage): Promise<void> {`);
  lines.push(`  if (!isValidEmail(msg.to)) {`);
  lines.push("    throw new Error(`Invalid recipient address: ${msg.to.slice(0, 64)}`);");
  lines.push(`  }`);
  lines.push(`  if (PROVIDER === "log") {`);
  lines.push(`    console.log(\`[notify] \${msg.subject} → \${msg.to}\`);`);
  lines.push(`    return;`);
  lines.push(`  }`);
  lines.push(`  if (PROVIDER === "resend") {`);
  lines.push(`    const res = await fetch("https://api.resend.com/emails", {`);
  lines.push(`      method: "POST",`);
  lines.push(`      headers: { "Authorization": \`Bearer \${API_KEY}\`, "Content-Type": "application/json" },`);
  lines.push(`      body: JSON.stringify({ from: FROM_EMAIL, to: msg.to, subject: msg.subject, html: msg.body }),`);
  lines.push(`    });`);
  lines.push(`    if (!res.ok) throw new Error(\`Resend error: \${res.status}\`);`);
  lines.push(`    return;`);
  lines.push(`  }`);
  lines.push(`  if (PROVIDER === "sendgrid") {`);
  lines.push(`    const res = await fetch("https://api.sendgrid.com/v3/mail/send", {`);
  lines.push(`      method: "POST",`);
  lines.push(`      headers: { "Authorization": \`Bearer \${API_KEY}\`, "Content-Type": "application/json" },`);
  lines.push(`      body: JSON.stringify({ personalizations: [{ to: [{ email: msg.to }] }], from: { email: FROM_EMAIL }, subject: msg.subject, content: [{ type: "text/html", value: msg.body }] }),`);
  lines.push(`    });`);
  lines.push(`    if (!res.ok) throw new Error(\`SendGrid error: \${res.status}\`);`);
  lines.push(`    return;`);
  lines.push(`  }`);
  lines.push(`  if (PROVIDER === "webhook") {`);
  lines.push(`    // Email-style notifications still flow through the webhook so the receiver sees a uniform shape.`);
  lines.push(`    await sendWebhook({ kind: "email", to: msg.to, subject: msg.subject, body: msg.body });`);
  lines.push(`    return;`);
  lines.push(`  }`);
  lines.push(`}`);
  lines.push(``);
  // Webhook signing. We use HMAC-SHA256 over the raw body for tamper detection.
  // Receivers verify with the same secret.
  lines.push(`import { createHmac } from "crypto";`);
  lines.push(``);
  lines.push(`function signPayload(body: string): string {`);
  lines.push(`  if (!WEBHOOK_SECRET) return "";`);
  lines.push(`  return createHmac("sha256", WEBHOOK_SECRET).update(body).digest("hex");`);
  lines.push(`}`);
  lines.push(``);
  lines.push(`/**`);
  lines.push(` * Send a JSON payload to NOTIFY_WEBHOOK_URL.`);
  lines.push(` *`);
  lines.push(` * Headers:`);
  lines.push(` *   Content-Type: application/json`);
  lines.push(` *   X-BoneScript-Signature: <hex hmac-sha256(body, WEBHOOK_SECRET)>  (only if secret set)`);
  lines.push(` *   X-BoneScript-Event: <event type>  (set by event handlers)`);
  lines.push(` */`);
  lines.push(`export async function sendWebhook(payload: Record<string, unknown>, eventType?: string): Promise<void> {`);
  lines.push(`  if (PROVIDER === "log") {`);
  lines.push(`    console.log(\`[notify:webhook] \${eventType || payload.kind || "event"}\`, JSON.stringify(payload).slice(0, 200));`);
  lines.push(`    return;`);
  lines.push(`  }`);
  lines.push(`  if (!WEBHOOK_URL) {`);
  lines.push(`    throw new Error("NOTIFY_WEBHOOK_URL is not configured");`);
  lines.push(`  }`);
  lines.push(`  // Validate URL — only http(s) and reject obvious attempts at SSRF (loopback / RFC1918).`);
  lines.push(`  let url: URL;`);
  lines.push(`  try { url = new URL(WEBHOOK_URL); }`);
  lines.push(`  catch { throw new Error("Invalid NOTIFY_WEBHOOK_URL"); }`);
  lines.push(`  if (url.protocol !== "https:" && url.protocol !== "http:") {`);
  lines.push(`    throw new Error(\`Webhook URL protocol must be http(s), got \${url.protocol}\`);`);
  lines.push(`  }`);
  lines.push(`  const body = JSON.stringify(payload);`);
  lines.push(`  const headers: Record<string, string> = { "Content-Type": "application/json" };`);
  lines.push(`  const sig = signPayload(body);`);
  lines.push(`  if (sig) headers["X-BoneScript-Signature"] = sig;`);
  lines.push(`  if (eventType) headers["X-BoneScript-Event"] = eventType;`);
  lines.push(`  const res = await fetch(WEBHOOK_URL, { method: "POST", headers, body });`);
  lines.push(`  if (!res.ok) throw new Error(\`Webhook delivery failed: \${res.status}\`);`);
  lines.push(`}`);
  lines.push(``);

  // Per-event handlers — payload is JSON-stringified and HTML-escaped before
  // being placed inside <pre> so payload values like "<script>..." can't break
  // out of the body.
  for (const event of system.events) {
    const eventName = toPascalCase(event.name);
    lines.push(`// Handler for ${eventName}`);
    lines.push(`export async function notify${eventName}(event: SystemEvent, recipientEmail: string): Promise<void> {`);
    lines.push(`  const __payload = escapeHtml(JSON.stringify(event.payload, null, 2));`);
    lines.push(`  await sendEmail({`);
    lines.push(`    to: recipientEmail,`);
    lines.push(`    subject: "${eventName} notification",`);
    lines.push("    body: `<p>Event <strong>${escapeHtml(\"" + eventName + "\")}</strong> occurred.</p><pre>${__payload}</pre>`,");
    lines.push(`  });`);
    lines.push(`}`);
    lines.push(``);
  }

  // registerNotificationHandlers
  lines.push(`export function registerNotificationHandlers(eventBus: any): void {`);
  lines.push(`  // TODO: implement recipient lookup per event type`);
  for (const event of system.events) {
    const eventName = toPascalCase(event.name);
    lines.push(`  // eventBus.subscribe("${eventName}", async (event: SystemEvent) => {`);
    lines.push(`  //   const recipientEmail = await lookupRecipient(event);`);
    lines.push(`  //   await notify${eventName}(event, recipientEmail);`);
    lines.push(`  // });`);
  }
  lines.push(`}`);
  lines.push(``);

  return lines.join("\n");
}
